# shellcheck shell=bash
# ai-revive — enable/disable/status: wire the plugin into byobu (or a plain ~/.tmux.conf) and
# manage the systemd user timer. Everything is per user; byobu has no system-wide drop-in.
#
# Byobu greps its user .tmux.conf for two option names (the ones that set the pane shell) and
# changes its launch behaviour when it finds them, so this file never spells them out.
# SPDX-License-Identifier: GPL-3.0-or-later

AI_REVIVE_BLOCK_BEGIN='# >>> ai-revive >>>'
AI_REVIVE_BLOCK_END='# <<< ai-revive <<<'

byobu_config_dir() {
	if [ -n "${BYOBU_CONFIG_DIR:-}" ]; then printf '%s' "$BYOBU_CONFIG_DIR"
	elif [ -d "$HOME/.byobu" ]; then printf '%s' "$HOME/.byobu"
	else printf '%s' "${XDG_CONFIG_HOME:-$HOME/.config}/byobu"
	fi
}
flavour_default() {
	if [ "${AI_REVIVE_FLAVOUR:-}" = byobu ] || command -v byobu >/dev/null 2>&1; then echo byobu; else echo tmux; fi
}
flavour_conf() {
	case $1 in
		byobu) printf '%s/.tmux.conf' "$(byobu_config_dir)" ;;
		tmux) printf '%s/.tmux.conf' "$HOME" ;;
		*) return 1 ;;
	esac
}
block_line() { printf 'run-shell -b "%s/ai-revive.tmux"' "$AI_REVIVE_HOME"; }

# block_strip FILE -> stdout without our block (awk always newline-terminates, so appending is safe)
block_strip() {
	[ -e "$1" ] || return 0
	awk -v b="$AI_REVIVE_BLOCK_BEGIN" -v e="$AI_REVIVE_BLOCK_END" '$0 == b {skip = 1} !skip {print} $0 == e {skip = 0}' "$1"
}
block_present() { [ -e "$1" ] && grep -qxF "$AI_REVIVE_BLOCK_BEGIN" "$1"; }
block_upsert() {
	local file=$1 tmp
	mkdir -p "$(dirname "$file")"
	tmp=$(mktemp)
	block_strip "$file" > "$tmp"
	{ cat "$tmp"; printf '%s\n%s\n%s\n' "$AI_REVIVE_BLOCK_BEGIN" "$(block_line)" "$AI_REVIVE_BLOCK_END"; } > "$file"
	rm -f "$tmp"
}
block_remove() {
	local file=$1 tmp
	block_present "$file" || return 0
	tmp=$(mktemp)
	block_strip "$file" > "$tmp"
	cat "$tmp" > "$file"
	rm -f "$tmp"
}

# ---------------------------------------------------------------- systemd user units
systemd_available() {
	[ "${AI_REVIVE_NO_SYSTEMD:-0}" != 1 ] && command -v systemctl >/dev/null 2>&1 && systemctl --user is-system-running >/dev/null 2>&1
}
user_unit_dir() { printf '%s/systemd/user' "${XDG_CONFIG_HOME:-$HOME/.config}"; }
# systemd_install_units: use the packaged units when systemd can see them, otherwise generate
# per-user copies that point at this checkout (e.g. a TPM install or `make install PREFIX=~/.local`).
systemd_install_units() {
	local u dir
	local frag exe
	frag=$(systemctl --user show -p FragmentPath --value ai-revive-save.service 2>/dev/null || true)
	if [ -n "$frag" ] && [ -r "$frag" ] && ! grep -q 'generated by ai-revive' "$frag"; then
		# packaged units: trust them only if the executable they name exists
		exe=$(sed -n 's/^ExecStart=\([^ ]*ai-revive\) .*/\1/p' "$frag" | head -1)
		[ -n "$exe" ] && [ -x "$exe" ] && return 0
	fi
	dir=$(user_unit_dir)
	mkdir -p "$dir"
	for u in "$AI_REVIVE_HOME"/systemd/user/*; do
		{ echo "# generated by ai-revive enable from $u"; sed -E "s|^(Exec(Start\|Stop)=)[^ ]*ai-revive |\1$AI_REVIVE_BIN |" "$u"; } > "$dir/$(basename "$u")"
	done
	systemctl --user daemon-reload
}
systemd_enable() {
	systemd_install_units
	local dropin
	dropin=$(user_unit_dir)/ai-revive-save.timer.d
	if [ "${SAVE_INTERVAL_MIN:-5}" != 5 ]; then
		mkdir -p "$dropin"
		printf '[Timer]\nOnBootSec=\nOnUnitActiveSec=\nOnBootSec=%smin\nOnUnitActiveSec=%smin\n' "$SAVE_INTERVAL_MIN" "$SAVE_INTERVAL_MIN" > "$dropin/interval.conf"
	else
		rm -f "$dropin/interval.conf"
	fi
	systemctl --user daemon-reload
	systemctl --user enable --now ai-revive-save.timer ai-revive-shutdown.service >/dev/null
	log_info "systemd user timer enabled (every ${SAVE_INTERVAL_MIN:-5} min) and shutdown hook armed"
}
systemd_disable() {
	systemctl --user disable --now ai-revive-save.timer ai-revive-shutdown.service >/dev/null 2>&1 || true
	local dir u
	dir=$(user_unit_dir)
	for u in "$dir"/ai-revive-*.service "$dir"/ai-revive-*.timer; do
		[ -e "$u" ] && grep -q 'generated by ai-revive' "$u" && rm -f "$u"
	done
	rm -rf "$dir/ai-revive-save.timer.d"
	systemctl --user daemon-reload 2>/dev/null || true
}

# ---------------------------------------------------------------- commands
cmd_enable() {
	local flavour="" file
	while [ $# -gt 0 ]; do
		case $1 in
			--byobu) flavour=byobu ;;
			--tmux) flavour=tmux ;;
			-q|--quiet) quiet_on ;;
			*) die "usage: ai-revive enable [--byobu|--tmux]" ;;
		esac
		shift
	done
	[ -n "$flavour" ] || flavour=$(flavour_default)
	file=$(flavour_conf "$flavour")
	if block_present "$file" && grep -qF "$(block_line)" "$file"; then
		log_info "already enabled in $file"
	else
		block_upsert "$file"
		log_info "enabled in $file ($flavour)"
	fi
	if has_server; then
		"$AI_REVIVE_HOME/ai-revive.tmux" || log_warn "could not install hooks on the running server"
		log_info "hooks and key bindings installed on the running server (prefix+$KEY_SAVE saves, prefix+$KEY_RESTORE restores)"
	else
		log_info "hooks will be installed when the next tmux server starts"
	fi
	if systemd_available; then
		systemd_enable
	else
		log_info "no systemd user session: periodic saves are limited to tmux hooks and prefix+$KEY_SAVE"
	fi
}

cmd_disable() {
	local f
	for f in "$(flavour_conf byobu)" "$(flavour_conf tmux)"; do
		if block_present "$f"; then block_remove "$f"; log_info "removed from $f"; fi
	done
	if has_server; then cmd_hook remove; fi
	if systemd_available; then systemd_disable; log_info "systemd user timer disabled"; fi
}

cmd_status() {
	local f last spid marker
	echo "ai-revive $(cmd_version) — $AI_REVIVE_HOME"
	for f in "$(flavour_conf byobu)" "$(flavour_conf tmux)"; do
		if block_present "$f"; then echo "enabled in:    $f"; fi
	done
	block_present "$(flavour_conf byobu)" || block_present "$(flavour_conf tmux)" || echo "enabled in:    nowhere (run: ai-revive enable)"
	if has_server; then
		spid=$(server_pid)
		echo "tmux server:   pid $spid, $(tmux_cmd list-sessions -F x | wc -l) session(s), $(tmux_cmd list-panes -a -F "#{pane_id}" | sort -u | wc -l) pane(s)"
		echo "hooks:         $(tmux_cmd show-hooks -g 2>/dev/null | grep -c "\[$AI_REVIVE_HOOK_INDEX\]") of $(wc -w <<< "$AI_REVIVE_HOOKS") installed"
		marker=$(restore_marker)
		if [ -e "$marker" ]; then
			echo "auto-restore:  ran for this server"
		elif save_restore_pending; then
			echo "auto-restore:  not run for this server; the snapshot is from a previous boot, so saves are held until ai-revive restore runs"
		else
			echo "auto-restore:  not run for this server"
		fi
	else
		echo "tmux server:   not running"
	fi
	if systemd_available; then
		echo "save timer:    $(systemctl --user is-active ai-revive-save.timer 2>/dev/null || true) ($(systemctl --user list-timers ai-revive-save.timer --no-legend 2>/dev/null | awk '{print $1, $2, $3, $4}' | head -1))"
	else
		echo "save timer:    systemd user session not available"
	fi
	if last=$(snapshot_resolve last 2>/dev/null); then
		echo "last snapshot: $(basename "$last" .json), $(( ($(date +%s) - $(stat -c %Y "$last")) / 60 )) min ago: $(snapshot_summary "$last")"
	else
		echo "last snapshot: none"
	fi
	echo "config:        $(config_dir)/config (AUTO_RESTORE=$AUTO_RESTORE, SAVE_INTERVAL_MIN=$SAVE_INTERVAL_MIN)"
	echo "log:           $(log_file)"
}
